  /// Asynchronously loads all 867 Synaxarium commemorations & saints into the directory
  static Future<void> ensureLoaded() async {
    if (_synaxariumLoaded) return;
    try {
      final raw = await rootBundle.loadString('assets/data/synaxarium_ar.json');
      final Map<String, dynamic> data = jsonDecode(raw);
      final List<PatronSaintProfile> dynamicSaints = [];
      final Set<String> seenNames = curatedSaints.map((s) => s.name).toSet();

      for (final entry in data.entries) {
        final parts = entry.key.split('-');
        final mIdx = (int.tryParse(parts[0]) ?? 1) - 1;
        final dayNum = int.tryParse(parts.length > 1 ? parts[1] : '1') ?? 1;
        final monthName = (mIdx >= 0 && mIdx < _copticMonths.length) ? _copticMonths[mIdx] : 'توت';
        final feastDate = '$dayNum $monthName';

        final items = entry.value as List? ?? [];
        for (int i = 0; i < items.length; i++) {
          final item = Map<String, dynamic>.from(items[i]);
          final rawTitle = (item['title'] ?? '').toString().trim();
          final text = (item['text'] ?? '').toString().trim();
          if (rawTitle.isEmpty) continue;

          // Clean commemorative prefix to extract saint's clean name
          String cleanName = rawTitle
              .replaceFirst(RegExp(r'^(نياحة|استشهاد|إستشهاد|تذكار|تعييد)\s+'), '')
              .trim();
          if (cleanName.isEmpty) cleanName = rawTitle;
          if (seenNames.contains(cleanName) || seenNames.contains(rawTitle)) continue;
          seenNames.add(cleanName);

          final cat = _classifySynaxariumTitle(rawTitle, text);
          final emoji = _emojiForCategory(cat, rawTitle);
          final shortName = cleanName.length > 32 ? '${cleanName.substring(0, 32)}…' : cleanName;
          final quotes = _buildSynaxariumQuotes(cleanName, rawTitle, text, cat);

          dynamicSaints.add(
            PatronSaintProfile(
              id: 'syn_${entry.key}_$i',
              name: cleanName,
              shortName: shortName,
              title: '$rawTitle • سنكسار الكنيسة القبطية ($feastDate)',
              category: cat,
              feastDate: feastDate,
              intercessionPrayer: 'بصلوات وشفاعات $cleanName، يا رب أنعم لنا بمغفرة خطايانا. بركة صلواته المقدسة تكون معنا. آمين.',
              iconEmoji: emoji,
              biography: text,
              quotes: quotes,
            ),
          );
        }
      }

      _allSaintsCache = [...curatedSaints, ...dynamicSaints];
      _synaxariumLoaded = true;
    } catch (_) {
      // Fallback to curatedSaints in unit test environments if asset bundle isn't loaded
    }
  }

  static String _classifySynaxariumTitle(String title, String text) {
    if (title.contains('الملاك') || title.contains('ملائكة') || title.contains('الرسول') || title.contains('النبي')) {
      return 'الملائكة والرسل';
    }
    if (title.contains('القديسة') || title.contains('الشهيدة') || title.contains('العذراء') || title.contains('الأم ')) {
      return 'القديسات والأمهات';
    }
    if (title.contains('استشهاد') || title.contains('إستشهاد') || title.contains('الشهيد') || title.contains('الشهداء')) {
      return 'الشهداء والشهيدات';
    }
    if (title.contains('البابا') || title.contains('البطريرك') || title.contains('الأسقف') || title.contains('اسقف')) {
      return 'البطاركة والأساقفة';
    }
    if (title.contains('الأنبا') || title.contains('الانبا') || title.contains('الراهب') || title.contains('السائح') || title.contains('المتوحد')) {
      return 'آباء البرية والرهبان';
    }
    return 'قديسو السنكسار';
  }

  static String _emojiForCategory(String cat, String title) {
    if (cat == 'الملائكة والرسل') return '🪽';
    if (cat == 'الشهداء والشهيدات') return '🛡️';
    if (cat == 'آباء البرية والرهبان') return '⛰️';
    if (cat == 'البطاركة والأساقفة') return '🏛️';
    if (cat == 'القديسات والأمهات') return '🕊️';
    return '✝️';
  }

