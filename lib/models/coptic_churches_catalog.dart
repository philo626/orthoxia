  static List<String> churchesFor(String diocese) {
    final direct = churchesByDiocese[diocese];
    if (direct != null && direct.isNotEmpty) return direct;
    // Backward compatibility if a user saved an older diocese name
    for (final entry in churchesByDiocese.entries) {
      if (entry.key.contains(diocese) || diocese.contains(entry.key)) {
        return entry.value;
      }
    }
    return const [
      'كنيسة السيدة العذراء مريم',
      'كنيسة الشهيد مارجرجس',
