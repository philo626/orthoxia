  static PatronSaintProfile getSaintById(String id) {
    return saints.firstWhere(
      (s) => s.id == id,
      orElse: () => saints.first,
    );
  }

  /// Returns a deterministic daily rotating quote for the user's chosen Patron Saint!
  static PatronSaintQuote getDailyQuote(String saintId, [DateTime? date]) {
    final saint = getSaintById(saintId);
    final now = date ?? DateTime.now();
    final dayOfYear = now.difference(DateTime(now.year, 1, 1)).inDays;
    return saint.quotes[dayOfYear % saint.quotes.length];
  }
